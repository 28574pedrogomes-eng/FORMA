    await manage.goto('/#admin'); await manage.getByRole('button', { name: 'Produtos e stock' }).click();
    await manage.getByRole('button', { name: 'Gerir opções de Peça Browser Comércio' }).click();
    await manage.getByRole('button', { name: 'Nova variante' }).click();
