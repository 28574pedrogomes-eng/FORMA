    await expect(page.locator('.related-grid button')).toHaveCount(4);
    await page.getByRole('dialog').getByRole('button', { name: 'Adicionar ao carrinho' }).click();
    await page.getByRole('button', { name: 'Fechar', exact: true }).click();
    await page.getByRole('button', { name: 'Carrinho, 1 artigos' }).click();
    await page.getByRole('button', { name: 'Finalizar encomenda', exact: true }).click();
    await expect(page.getByLabel('Morada', { exact: true })).toHaveValue('Rua dos Testes, 42');
    await page.getByLabel('Tens um código de desconto?').fill(code);
    await page.getByRole('button', { name: 'Aplicar', exact: true }).click();
    await expect(page.locator('.discount-line')).toContainText('2,50');
    await expect(page.locator('.summary-line.total')).toContainText('27,40');
    await page.getByLabel('Resultado do pagamento de teste').selectOption('refused');
    await page.getByRole('checkbox', { name: /Compreendo que esta é uma loja de demonstração/ }).check();
    await page.screenshot({ path: 'storage/verified-checkout.png', animations: 'disabled' });
    await page.getByRole('button', { name: 'Confirmar encomenda' }).click();
    await expect(page.locator('.payment-badge')).toContainText('Recusado');
    await page.getByRole('button', { name: 'Ver as minhas encomendas' }).click();
    await page.getByRole('button', { name: 'Resolver pagamento' }).click();
    await page.getByRole('button', { name: 'Simular resultado' }).click();
    await expect(page.locator('.payment-badge')).toContainText('Aprovado');
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Comprovativo PDF' }).click();
    const download = await downloadPromise;
    expect(readFileSync(await download.path()).subarray(0, 8).toString()).toBe('%PDF-1.4');
    const [order] = await buyer('/orders');
    for (const status of ['processing', 'shipped', 'delivered']) await api(`/admin/orders/${order.id}`, 'PATCH', { status });
    await page.getByRole('link', { name: 'FORMA, início' }).click();
    await page.getByRole('combobox', { name: 'Pesquisar produtos' }).fill('Peça Browser Comércio');
    await page.getByRole('button', { name: 'Ver Peça Browser Comércio', exact: true }).click();
    await page.getByRole('button', { name: 'Escrever avaliação' }).click();
    await page.getByLabel('4 estrelas', { exact: true }).check();
    await page.getByLabel('A tua experiência').fill('Uma compra verificada com fotografia e quatro estrelas.');
    await page.getByLabel('Fotografia da avaliação').setInputFiles({ name: 'test.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jG1sAAAAASUVORK5CYII=', 'base64') });
    await page.getByRole('button', { name: 'Guardar avaliação' }).click();
    await expect(page.locator('.review-list')).toContainText('Uma compra verificada');
