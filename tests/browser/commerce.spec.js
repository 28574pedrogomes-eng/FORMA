    await manage.getByLabel('Stock da opção').fill('1');
    await manage.getByRole('button', { name: 'Guardar variante' }).click();
    await expect(manage.locator('.variant-admin-list')).toContainText('Cinza / Grande');
    await manage.getByRole('button', { name: 'Fechar', exact: true }).click();
    await manage.getByRole('button', { name: 'Cupões', exact: true }).click();
    await manage.getByRole('button', { name: 'Novo cupão', exact: true }).click();
    await manage.getByLabel('Código', { exact: true }).fill(code);
    await manage.getByLabel('Desconto (%)').fill('10');
    await manage.getByRole('button', { name: 'Guardar cupão' }).click();
    await expect(manage.getByRole('row').filter({ hasText: code })).toContainText('10%');
    couponId = (await api('/admin/coupons')).find(c => c.code === code).id;

    await buyer('/session'); await buyer('/auth/register', 'POST', { name: 'Cliente Browser Comércio', email: `forma-test-advanced-${Date.now()}@example.test`, password: 'BrowserSeguro!123' });
    await page.goto('/#account'); await page.getByRole('button', { name: 'Nova morada' }).click();
    await page.getByLabel('Destinatário').fill('Cliente Browser Comércio');
    await page.getByLabel('Morada', { exact: true }).fill('Rua dos Testes, 42');
    await page.getByLabel('Código postal').fill('4000-001');
    await page.getByLabel('Localidade').fill('Porto'); await page.getByLabel('Telefone').fill('912345678');
    await page.getByRole('button', { name: 'Guardar morada' }).click();
    await expect(page.locator('.saved-address')).toContainText('Rua dos Testes, 42');
    await page.getByRole('link', { name: 'FORMA, início' }).click();
    await page.getByRole('combobox', { name: 'Pesquisar produtos' }).fill('Peça Browser Comércio');
    await page.getByRole('button', { name: 'Guardar Peça Browser Comércio nos favoritos' }).click();
    await expect(page.getByRole('button', { name: 'Remover Peça Browser Comércio dos favoritos' })).toBeVisible();
    await page.reload();
    await page.getByRole('combobox', { name: 'Pesquisar produtos' }).fill('Peça Browser Comércio');
    await expect(page.getByRole('button', { name: 'Remover Peça Browser Comércio dos favoritos' })).toBeVisible();
    await page.getByRole('button', { name: 'Ver Peça Browser Comércio', exact: true }).click();
    await page.getByRole('button', { name: /Cinza \/ Grande/ }).click();
