CREATE TABLE IF NOT EXISTS price_alerts (
 user_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NOT NULL,
 reference_price_cents INT UNSIGNED NOT NULL, initial_price_cents INT UNSIGNED NOT NULL,
 notification_count INT UNSIGNED NOT NULL DEFAULT 0, last_notified_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,product_id), INDEX(product_id,reference_price_cents),
 FOREIGN KEY(user_id,product_id) REFERENCES favorites(user_id,product_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS email_changes (
 user_id BIGINT UNSIGNED PRIMARY KEY, new_email VARCHAR(190) NOT NULL, old_email VARCHAR(190) NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, session_version INT UNSIGNED NOT NULL, expires_at DATETIME NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS product_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NULL, image VARCHAR(500) NOT NULL, alt VARCHAR(160) NOT NULL DEFAULT '', position INT UNSIGNED NOT NULL,
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE,
 FOREIGN KEY(variant_id) REFERENCES product_variants(id) ON DELETE CASCADE, INDEX(product_id,position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(30) NOT NULL, note VARCHAR(255) NOT NULL DEFAULT '', occurred_at DATETIME NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE, INDEX(order_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS support_attachments (
 id CHAR(32) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, message_id BIGINT UNSIGNED NULL,
 name VARCHAR(120) NOT NULL, mime VARCHAR(80) NOT NULL, size_bytes INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(message_id) REFERENCES support_messages(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS backups (
 id CHAR(32) PRIMARY KEY, size_bytes BIGINT UNSIGNED NOT NULL, sha256 CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, created_by BIGINT UNSIGNED NULL,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
